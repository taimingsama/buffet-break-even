const test = require('node:test')
const assert = require('node:assert/strict')
const {loadModule} = require('../helpers/runtime.cjs')
const create = () => loadModule('ui/composables/usePressFeedback').usePressFeedback()

test('短按松手后先完成缩小，再开始还原', () => {
  const feedback = create()
  feedback.press()
  assert.equal(feedback.phase.value, 'pressing')
  feedback.release()
  assert.equal(feedback.phase.value, 'pressing')
  feedback.animationEnd({animationName: 'press-in-scoped'})
  assert.equal(feedback.phase.value, 'releasing')
  feedback.animationEnd({animationName: 'press-out-scoped'})
  assert.equal(feedback.phase.value, 'idle')
})

test('小程序同一节点的 target/currentTarget 对象不同，仍能正常还原', () => {
  const feedback = create()
  feedback.press({type:'touchstart'})
  feedback.release({type:'touchend'})
  feedback.animationEnd({detail:{animationName:'press-in'},target:{id:'add'},currentTarget:{id:'add'}})
  assert.equal(feedback.phase.value,'releasing')
  feedback.animationEnd({detail:{animationName:'press-out'},target:{id:'add'},currentTarget:{id:'add'}})
  assert.equal(feedback.phase.value,'idle')
})

test('缺少动画结束事件也会还原，长按仍保持缩小', async t => {
  t.mock.timers.enable({apis:['setTimeout']})
  const {nextTick} = require('vue')
  const feedback = create()
  feedback.press()
  feedback.release()
  await nextTick()
  t.mock.timers.tick(152)
  assert.equal(feedback.phase.value,'releasing')
  await nextTick()
  t.mock.timers.tick(152)
  assert.equal(feedback.phase.value,'idle')
  feedback.press()
  await nextTick()
  t.mock.timers.tick(152)
  assert.equal(feedback.phase.value,'held')
  feedback.release()
  assert.equal(feedback.phase.value,'releasing')
  await nextTick()
  t.mock.timers.tick(152)
  assert.equal(feedback.phase.value,'idle')
})

test('长按保持缩小，松手立即开始还原，取消触摸同样释放', () => {
  const feedback = create()
  feedback.press({type:'touchstart'})
  feedback.animationEnd({detail:{animationName:'press-in'}})
  assert.equal(feedback.phase.value, 'held')
  feedback.release({type:'touchcancel'})
  assert.equal(feedback.phase.value, 'releasing')
})

test('触摸后的合成鼠标事件不会重播动画，旧动画结束事件不影响新的按压', () => {
  const feedback = create()
  feedback.press({type:'touchstart'})
  feedback.release({type:'touchend'})
  feedback.animationEnd({animationName:'press-in'})
  feedback.press({type:'mousedown',button:0})
  assert.equal(feedback.phase.value, 'releasing')
  feedback.animationEnd({animationName:'press-out'})
  feedback.press({type:'touchstart'})
  feedback.animationEnd({animationName:'press-out'})
  assert.equal(feedback.phase.value, 'pressing')
})
